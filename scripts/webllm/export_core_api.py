#!/usr/bin/env python3
"""Export exact Core data/context and theorem headers, with proof bodies omitted."""
import hashlib
from pathlib import Path
import verify_phase_a as verifier

MODULES = ["A01FourierCharacters", "Ch03Fourier", "Ch10Heisenberg", "A05MultiSpecies", "Ch14Mandelstam"]


def main():
    parts = ["# CH15 exact Core API context\n\nGenerated by scripts/webllm/export_core_api.py. "
             "Definitions/context and theorem headers are copied through the v2 parser; proof bodies are omitted. "
             "The hashes identify the actual complete sources. Import Bosonize to use their compiled declarations. "
             "This document supplies API context, not additional assumptions or replacement definitions.\n"]
    for module in MODULES:
        source = verifier.REPO / "Bosonize/Core" / f"{module}.lean"
        text = source.read_text(encoding="utf-8")
        model = verifier.lean.parse_lean(text)
        parts.append(f"\n## {source.relative_to(verifier.REPO)}\n\nSHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}\n")
        parts.append("\n### Complete data and context commands\n\n```text\n" +
                     "\n\n".join(command.text for command in model.commands) + "\n```\n")
        parts.append("\n### Proved declaration headers (bodies omitted)\n\n```text\n" +
                     "\n\n".join(item.text for item in model.lemmas.values()) + "\n```\n")
    target = verifier.REPO / "docs/webllm/ch15_core_api.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(parts), encoding="utf-8")
    print(f"Exported {target}: {target.stat().st_size} bytes")


if __name__ == "__main__":
    main()
