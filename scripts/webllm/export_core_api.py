#!/usr/bin/env python3
"""Export every frozen Core API in source order, with focused CH15 proof examples."""
import hashlib
import json
from pathlib import Path
import verify_phase_a as verifier

# Bodies are copied exactly from frozen Core, never synthesized as proof advice.
EXAMPLES = {
    'A01FourierCharacters': {'residue_character_int_cast', 'residue_character_add_right',
                             'character_sum', 'complex_character_conj'},
    'A03EnergyBudgets': {'ket_mem_coordinate_space', 'coordinate_space_support'},
    'Ch07VacuumBudget': {'excitation_nonneg', 'ket_mem_fixed_budget', 'species_budget_ket'},
    'A05MultiSpecies': {'tensor_kets', 'rho_tensor', 'rho_adjoint', 'rho_cross_commute',
                        'rho_budget_map', 'ground_mem_budget', 'ground_ne_zero'},
}


def excerpt(text, examples):
    """Keep original command order/context; omit only unselected theorem bodies."""
    model = verifier.lean.parse_lean(text)
    lines = text.splitlines(keepends=True)
    records = [(command.line, None, command) for command in model.commands]
    records += [(lemma.line, name.split('.')[-1], lemma) for name, lemma in model.lemmas.items()]
    records.sort(key=lambda item: item[0])
    parts, found = [], set()
    for index, (line, name, record) in enumerate(records):
        next_line = records[index + 1][0] if index + 1 < len(records) else len(lines) + 1
        if name in examples:
            found.add(name)
            # Parser line numbers retain original newlines; token offsets do not.
            parts.append(''.join(lines[line - 1:next_line - 1]).rstrip())
        elif name is not None:
            parts.append(record.text + '\n-- proof body omitted')
        else:
            parts.append(record.text)
    if found != examples:
        raise ValueError(f'Missing proof examples: {sorted(examples - found)}')
    return '\n\n'.join(parts)


def render(repo=verifier.REPO):
    hashes = json.loads((repo / 'docs/spec/core_locks.json').read_text())
    actual = {p.relative_to(repo).as_posix() for p in (repo / 'Bosonize/Core').rglob('*.lean')}
    if actual != set(hashes):
        raise ValueError('Core inventory differs from the complete-source lock')
    guide = (repo / 'docs/webllm/ch15_phase_b_context_guide.md').read_text()
    target = verifier.lean.parse_lean((repo / 'BosonizeStubs/A06ChiralFields.lean').read_text())
    missing = [name for name in target.lemmas if '`' + name.split('.')[-1] + '`' not in guide]
    if missing:
        raise ValueError(f'Guide misses target obligations: {missing}')
    parts = ['# CH15 complete Core API and focused proof context\n\n'
             'Generated by scripts/webllm/export_core_api.py. Every frozen Core module is included. '
             'Definitions, instances, attributes, namespaces, sections and theorem headers retain '
             'their original command order and local context. Selected existing proofs are copied '
             'verbatim; other proof bodies are omitted. These text excerpts are API references, '
             'not standalone compilable Lean files. This export proves no new theorem.\n', guide]
    for name in sorted(hashes):
        source = repo / name
        blob = source.read_bytes()
        if hashlib.sha256(blob).hexdigest() != hashes[name]:
            raise ValueError(f'Frozen Core hash mismatch: {name}')
        examples = EXAMPLES.get(source.stem, set())
        parts.append(f'\n## {name}\n\nFull source SHA-256: {hashes[name]}\n'
                     f'Included full proofs: {", ".join(sorted(examples)) or "none"}.\n\n```text\n' +
                     excerpt(blob.decode('utf-8'), examples) + '\n```\n')
    return '\n'.join(parts)


def main():
    target = verifier.REPO / 'docs/webllm/ch15_core_api.md'
    content = render()
    target.write_text(content, encoding='utf-8')
    print(f'Exported {target}: {len(content.encode("utf-8"))} bytes')


if __name__ == '__main__':
    main()
